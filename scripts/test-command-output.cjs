const assert=require('node:assert/strict');
const {createCommandOutput,redactLive}=require('../desktop/command-output.cjs');
const capture=createCommandOutput(['secret-test']);
capture.append('stdout',Buffer.from('hello sec'));
assert.equal(capture.snapshot().stdout,'hello ');
capture.append('stdout',Buffer.from('ret-test world'));
assert.equal(capture.snapshot().stdout,'hello [凭据已隐藏] world');
assert.equal(redactLive('aaaa',['aaa']), '');
const unicode=createCommandOutput([]),bytes=Buffer.from('中文');
unicode.append('stderr',bytes.subarray(0,2));assert.equal(unicode.snapshot().stderr,'');
unicode.append('stderr',bytes.subarray(2));assert.equal(unicode.snapshot().stderr,'中文');
const bounded=createCommandOutput(['password'],5);bounded.append('stdout',Buffer.from('password'));
assert.equal(bounded.snapshot().stdout,'');assert.equal(bounded.snapshot().truncated,true);
const {spawn}=require('node:child_process');
const child=spawn(process.execPath,['-e',"process.stdout.write('first\\n');setTimeout(()=>process.stderr.write('second\\n'),150)"]);
const streamed=createCommandOutput([]);let sawBeforeClose=false;
child.stdout.on('data',data=>{streamed.append('stdout',data);sawBeforeClose=streamed.snapshot().stdout.includes('first');});
child.stderr.on('data',data=>streamed.append('stderr',data));
child.on('close',code=>{assert.equal(code,0);assert.ok(sawBeforeClose);assert.equal(streamed.snapshot().stderr,'second\n');console.log('Command streaming, UTF-8, bounds and split credential redaction passed');});
